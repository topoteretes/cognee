#!/usr/bin/env python3
"""Render the Connectors table of README.md from inventory.yml.

The table sits between the ``<!-- inventory:start -->`` and ``<!-- inventory:end -->``
markers of README.md and is regenerated in place; nothing outside the markers changes.
Columns: Connector, Package, Auth, Sources, cognee server, Cloud, Status.

Usage:
    python scripts/render_inventory.py           # rewrite the table
    python scripts/render_inventory.py --check   # exit 1 when README.md is stale (CI)

Exit status with ``--check``: 0 when the README is current, 1 when it is stale or the
markers are missing.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

from packages import REPO_ROOT
from validate_inventory import DEFAULT_INVENTORY, InventoryError, load_inventory

START_MARKER = "<!-- inventory:start -->"
END_MARKER = "<!-- inventory:end -->"
GENERATED_NOTE = (
    "<!-- Generated by scripts/render_inventory.py from inventory.yml; do not edit by hand. -->"
)
COLUMNS = ("Connector", "Package", "Auth", "Sources", "cognee server", "Cloud", "Status")
DEFAULT_README = REPO_ROOT / "README.md"


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _yes(flag: Any) -> str:
    return "✅" if flag is True else "—"


def render_table(entries: list[dict[str, Any]]) -> str:
    """The Markdown between the markers (markers excluded), for the given entries."""
    if not entries:
        return (
            f"{GENERATED_NOTE}\n\n"
            "_No connectors yet. Scaffold one with "
            '`python scripts/new_connector.py <slug> --display-name "..."`._\n'
        )
    lines = [
        GENERATED_NOTE,
        "",
        "| " + " | ".join(COLUMNS) + " |",
        "| " + " | ".join("---" for _ in COLUMNS) + " |",
    ]
    for entry in sorted(entries, key=lambda item: str(item.get("display_name", "")).lower()):
        display_name = _cell(str(entry.get("display_name", entry.get("slug", ""))))
        directory = str(entry.get("directory", ""))
        status = str(entry.get("status", ""))
        package = str(entry.get("package", ""))
        connector = (
            f"[{display_name}]({directory})" if status != "planned" and directory else display_name
        )
        package_cell = (
            f"[`{package}`](https://pypi.org/project/{package}/)"
            if status == "ported"
            else f"`{package}`"
        )
        sources = ", ".join(f"`{source}`" for source in entry.get("sources") or []) or "—"
        hosts = entry.get("hosts") or {}
        lines.append(
            "| "
            + " | ".join(
                (
                    connector,
                    package_cell,
                    _cell(str(entry.get("auth", ""))),
                    sources,
                    _yes(hosts.get("cognee")),
                    _yes(hosts.get("cloud")),
                    _cell(status),
                )
            )
            + " |"
        )
    return "\n".join(lines) + "\n"


def render_readme(readme_text: str, entries: list[dict[str, Any]]) -> str:
    """``readme_text`` with the block between the markers replaced by the rendered table."""
    start = readme_text.find(START_MARKER)
    end = readme_text.find(END_MARKER)
    if start == -1 or end == -1 or end < start:
        raise ValueError(f"README is missing the {START_MARKER} / {END_MARKER} markers")
    head = readme_text[: start + len(START_MARKER)]
    tail = readme_text[end:]
    return f"{head}\n{render_table(entries)}{tail}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Render the README's connector table.")
    parser.add_argument(
        "--check", action="store_true", help="only report whether README.md is stale"
    )
    parser.add_argument(
        "--inventory", type=Path, default=DEFAULT_INVENTORY, help="the inventory file"
    )
    parser.add_argument("--readme", type=Path, default=DEFAULT_README, help="the README to update")
    args = parser.parse_args(argv)

    try:
        inventory = load_inventory(args.inventory)
    except (InventoryError, OSError) as error:
        print(f"error: {error}")
        return 1
    entries = (inventory or {}).get("connectors") or []
    current = args.readme.read_text(encoding="utf-8")
    try:
        rendered = render_readme(current, entries)
    except ValueError as error:
        print(f"error: {error}")
        return 1

    if rendered == current:
        print(f"{args.readme}: connector table is current ({len(entries)} entries).")
        return 0
    if args.check:
        print(f"{args.readme}: connector table is stale; run `python scripts/render_inventory.py`.")
        return 1
    args.readme.write_text(rendered, encoding="utf-8")
    print(f"{args.readme}: connector table rewritten ({len(entries)} entries).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
