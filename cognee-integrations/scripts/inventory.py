#!/usr/bin/env python3
"""Check integrations/inventory.yml and render the plugin table of README.md from it.

Checks:
- every plugin folder under integrations/ has exactly one entry, and every entry's
  folder exists (conformance/ and tests/ are shared, not plugins);
- each entry has every field, ``path`` is ``integrations/<slug>``, ``tag_prefix`` is
  ``<slug>-v`` and ``release_workflow`` exists in .github/workflows/;
- ``package_name`` and ``current_version`` match the plugin's pyproject.toml
  (python) or package.json (typescript).

Usage, from any directory:
    python cognee-integrations/scripts/inventory.py          # check, then rewrite the table
    python cognee-integrations/scripts/inventory.py --check  # exit 1 on an error or a stale table

Needs Python 3.11+ (tomllib) and PyYAML.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import tomllib
import yaml

ROOT = Path(__file__).resolve().parent.parent
REPO_ROOT = ROOT.parent
INVENTORY = ROOT / "integrations" / "inventory.yml"
README = ROOT / "README.md"
SHARED_FOLDERS = {"conformance", "tests"}
FIELDS = (
    "slug",
    "name",
    "language",
    "registry",
    "package_name",
    "cognee_dependency",
    "current_version",
    "path",
    "tag_prefix",
    "release_workflow",
    "moved_from",
)
START_MARKER = "<!-- inventory:start -->"
END_MARKER = "<!-- inventory:end -->"
GENERATED_NOTE = (
    "<!-- Generated by scripts/inventory.py from integrations/inventory.yml;"
    " do not edit by hand. -->"
)
PACKAGE_URLS = {
    "pypi": "https://pypi.org/project/{}/",
    "npm": "https://www.npmjs.com/package/{}",
}


def load_entries() -> list[dict[str, Any]]:
    data = yaml.safe_load(INVENTORY.read_text(encoding="utf-8"))
    entries = data.get("integrations") if isinstance(data, dict) else None
    if not isinstance(entries, list):
        raise SystemExit(f"{INVENTORY}: expected a top-level `integrations:` list")
    return entries


def manifest_identity(entry: dict[str, Any]) -> tuple[str | None, str | None]:
    """The (package name, version) the plugin's own manifest declares."""
    folder = ROOT / entry["path"]
    if entry["language"] == "python":
        project = tomllib.loads((folder / "pyproject.toml").read_text(encoding="utf-8"))
        project = project.get("project", {})
    elif entry["language"] == "typescript":
        project = json.loads((folder / "package.json").read_text(encoding="utf-8"))
    else:
        return None, None
    return project.get("name"), project.get("version")


def check(entries: list[dict[str, Any]]) -> list[str]:
    errors: list[str] = []
    seen: set[str] = set()
    for index, entry in enumerate(entries):
        if not isinstance(entry, dict):
            errors.append(f"entry {index} is not a mapping")
            continue
        missing = [field for field in FIELDS if field not in entry]
        unknown = sorted(set(entry) - set(FIELDS))
        slug = entry.get("slug", f"entry {index}")
        if missing:
            errors.append(f"{slug}: missing {', '.join(missing)}")
            continue
        if unknown:
            errors.append(f"{slug}: unknown fields {', '.join(unknown)}")
        if slug in seen:
            errors.append(f"{slug}: listed twice")
        seen.add(slug)
        if entry["path"] != f"integrations/{slug}":
            errors.append(f"{slug}: path must be integrations/{slug}")
        if entry["tag_prefix"] != f"{slug}-v":
            errors.append(f"{slug}: tag_prefix must be {slug}-v")
        if entry["language"] not in ("python", "typescript"):
            errors.append(f"{slug}: language must be python or typescript")
        if entry["registry"] not in ("pypi", "npm", "none"):
            errors.append(f"{slug}: registry must be pypi, npm or none")
        workflow = entry["release_workflow"]
        if workflow and not (REPO_ROOT / ".github" / "workflows" / workflow).is_file():
            errors.append(f"{slug}: release_workflow {workflow} is not in .github/workflows/")
        if not (ROOT / entry["path"]).is_dir():
            errors.append(f"{slug}: {entry['path']} does not exist")
            continue
        try:
            name, version = manifest_identity(entry)
        except (OSError, ValueError) as error:
            errors.append(f"{slug}: cannot read its manifest: {error}")
            continue
        if entry["registry"] != "none" and name != entry["package_name"]:
            errors.append(f"{slug}: package_name {entry['package_name']} != manifest name {name}")
        if version != str(entry["current_version"]):
            errors.append(
                f"{slug}: current_version {entry['current_version']} != manifest version {version}"
            )
    folders = {
        path.name
        for path in (ROOT / "integrations").iterdir()
        if path.is_dir() and path.name not in SHARED_FOLDERS and not path.name.startswith(".")
    }
    for folder in sorted(folders - seen):
        errors.append(f"integrations/{folder}/ has no entry in inventory.yml")
    return errors


def render_table(entries: list[dict[str, Any]]) -> str:
    rows = [
        "| Integration | Package | Version | Source | Release |",
        "|---|---|---|---|---|",
    ]
    for entry in sorted(entries, key=lambda e: e["name"].lower()):
        package = entry["package_name"]
        url = PACKAGE_URLS.get(entry["registry"])
        package_cell = f"[`{package}`]({url.format(package)})" if package and url else "—"
        workflow = entry["release_workflow"]
        release_cell = (
            f"[`{workflow}`](../.github/workflows/{workflow}), tags `{entry['tag_prefix']}*`"
            if workflow
            else "—"
        )
        rows.append(
            f"| {entry['name']} | {package_cell} | {entry['current_version']} "
            f"| [`{entry['path']}`]({entry['path']}) | {release_cell} |"
        )
    return "\n".join(rows)


def rendered_readme(entries: list[dict[str, Any]]) -> str:
    text = README.read_text(encoding="utf-8")
    start, end = text.find(START_MARKER), text.find(END_MARKER)
    if start < 0 or end < start:
        raise SystemExit(f"{README}: missing {START_MARKER} / {END_MARKER}")
    block = f"{START_MARKER}\n{GENERATED_NOTE}\n\n{render_table(entries)}\n\n"
    return text[:start] + block + text[end:]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail on errors or a stale table")
    args = parser.parse_args()

    entries = load_entries()
    errors = check(entries)
    for error in errors:
        print(f"::error file=cognee-integrations/integrations/inventory.yml::{error}")
    if errors:
        return 1
    expected = rendered_readme(entries)
    if args.check:
        if expected != README.read_text(encoding="utf-8"):
            print(
                "::error file=cognee-integrations/README.md::The plugin table is stale."
                " Run `python cognee-integrations/scripts/inventory.py` and commit the result."
            )
            return 1
        print(f"inventory.yml is valid ({len(entries)} plugins) and the README table is current.")
        return 0
    README.write_text(expected, encoding="utf-8")
    print(f"Rendered {len(entries)} plugins into {README}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
